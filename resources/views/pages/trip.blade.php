document.getElementById('generate-btn').addEventListener('click', function() {
    const termId = document.querySelector('#terminal-options .active').dataset.term;
    const hours = parseInt(document.querySelector('#duration-options .active').dataset.hours);
    
    // Show Loading
    const loading = document.getElementById('trip-loading');
    loading.style.display = 'flex';
    loading.style.opacity = '1';
    
    // Reset steps
    document.getElementById('ls-2').textContent = '⏳ Menghitung estimasi waktu & biaya';
    document.getElementById('ls-3').textContent = '⏳ Menyusun jadwal perjalanan';

    setTimeout(() => { document.getElementById('ls-2').textContent = '✅ Menghitung estimasi waktu & biaya'; }, 500);
    setTimeout(() => { document.getElementById('ls-3').textContent = '✅ Menyusun jadwal perjalanan'; }, 1000);

    setTimeout(() => {
        loading.style.opacity = '0';
        setTimeout(() => { loading.style.display = 'none'; renderItinerary(termId, hours); }, 500);
    }, 1500);
});

function renderItinerary(termId, hours) {
    const data = TERMINAL_DATA[termId];
    
    let spotCount = 2; // 4 hours
    if(hours === 6) spotCount = 3;
    if(hours === 8) spotCount = 4;

    const spotsToVisit = data.spots.slice(0, spotCount);
    let totalTicket = spotsToVisit.reduce((sum, spot) => sum + spot.price, 0);
    let totalFood = data.food.price;
    let totalTransport = 20000; // estimated transport budget
    let totalCost = totalTicket + totalFood + totalTransport;

    let html = `
    <div class="trip-layout">
        <div class="trip-timeline-wrap">
            <div class="trip-title-row" style="margin-bottom: 2rem;">
                <h2 class="trip-section-title">📅 Itinerary: ${data.name}</h2>
                <span class="trip-date-badge">Durasi: ${hours} Jam</span>
            </div>

            <div class="timeline" id="trip-timeline">
    `;

    // Render Stops
    spotsToVisit.forEach((spot, idx) => {
        html += `
        <div class="timeline-item">
            <div class="tl-time">
                <span class="tl-hr">${spot.timeLabel}</span>
                <span class="tl-period">WIB</span>
            </div>
            <div class="tl-connector"><div class="tl-dot"></div><div class="tl-line"></div></div>
            <div class="tl-card">
                <div class="tl-card-img">
                    <img src="${spot.img}" alt="${spot.name}" onerror="this.src='/images/placeholder.jpg'">
                </div>
                <div class="tl-card-body">
                    <div class="tl-badge-row">
                        <div class="tl-badge">Stop ${idx + 1}</div>
                    </div>
                    <h3>${spot.name}</h3>
                    <div class="tl-meta">
                        <span>⏱ ${spot.dur}</span>
                        <span>🎟 ${spot.price === 0 ? 'Gratis' : 'Rp ' + spot.price.toLocaleString('id-ID')}</span>
                        <span>📍 Jarak: ${spot.dist}</span>
                    </div>
                </div>
            </div>
        </div>
        `;

        // Insert Lunch & Prayer after Stop 2
        if (idx === 1) {
            html += `
            <div class="timeline-item">
                <div class="tl-time">
                    <span class="tl-hr">12:00</span>
                    <span class="tl-period">WIB</span>
                    <span class="tl-status tl-status-food">Ishoma</span>
                </div>
                <div class="tl-connector"><div class="tl-dot tl-dot-food"></div><div class="tl-line"></div></div>

                        <div style="background: #fff; padding: 1rem; border-radius: 8px; border: 1px solid #eee; display:flex; gap:1rem; align-items:center;">
                            <img src="${data.food.img}" style="width: 60px; height: 60px; border-radius: 8px; object-fit: cover;" onerror="this.src='/images/placeholder.jpg'">
                            <div>
                                <h4 style="margin:0;">🍽️ Rekomendasi Makan Siang: ${data.food.name}</h4>
                                <span style="font-size:0.85rem; color:#666;">Estimasi Biaya: Rp ${data.food.price.toLocaleString('id-ID')}</span>
                            </div>
                        </div>
                    </div>
                </div>
            </div>
            `;
        }
    });

    html += `
                <div class="tl-end">
                    <div class="tl-end-marker"><span>🏁</span></div>
                    <div class="tl-end-info">
                        <strong>Perjalanan Selesai</strong>
                        <span>Total ${spotsToVisit.length} Destinasi dikunjungi</span>
                    </div>
                </div>
            </div>
        </div>
        
        <!-- SIDEBAR -->
        <div class="trip-sidebar">
            <div class="sidebar-card">
                <div class="sidebar-card-header">
                    <h3>💰 Estimasi Biaya</h3>
                </div>
                <div class="cost-rows">
                    <div class="cost-row"><span>🎟 Tiket Destinasi</span><span>Rp ${totalTicket.toLocaleString('id-ID')}</span></div>
                    <div class="cost-row"><span>🍜 Makan & Minum</span><span>Rp ${totalFood.toLocaleString('id-ID')}</span></div>
                    <div class="cost-row"><span>🛵 Transportasi</span><span>~ Rp ${totalTransport.toLocaleString('id-ID')}</span></div>
